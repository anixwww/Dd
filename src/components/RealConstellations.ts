export const getRandomRealConstellation = (excludeId?: string): RealConstellation => {
  const available = REAL_CONSTELLATIONS.filter((c) => c.id !== excludeId);
  const pool = available.length > 0 ? available : REAL_CONSTELLATIONS;
  const index = Math.floor(Math.random() * pool.length);
  return pool[index];
};
